import { GoogleGenAI } from "@google/genai";

export const PRIMARY_MODEL = "gemini-3.8-flash";
export const FALLBACK_MODEL = "gemini-3.6-flash";

function getGenAIClient(): GoogleGenAI | null {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    return null;
  }
  return new GoogleGenAI({ apiKey });
}

export interface GenerateWithFallbackOptions {
  systemInstruction?: string;
  temperature?: number;
}

export interface ModelGenerationResult {
  text: string | null;
  modelUsed: string | null;
  success: boolean;
  error?: string;
}

/**
 * Generates content using Google Gen AI SDK with robust model fallback.
 *
 * 1. Tries PRIMARY_MODEL (gemini-3.8-flash).
 * 2. If it encounters any error (rate limit, overload, model unavailable), logs a warning
 *    and seamlessly falls back to FALLBACK_MODEL (gemini-3.6-flash).
 * 3. If both fail, catches the error gracefully without throwing unhandled exceptions.
 */
export async function generateWithModelFallback(
  contents: string | any,
  options?: GenerateWithFallbackOptions
): Promise<ModelGenerationResult> {
  const ai = getGenAIClient();
  if (!ai) {
    return {
      text: null,
      modelUsed: null,
      success: false,
      error: "GEMINI_API_KEY is not configured.",
    };
  }

  const requestConfig: Record<string, any> = {};
  if (options?.systemInstruction) {
    requestConfig.systemInstruction = options.systemInstruction;
  }
  if (typeof options?.temperature === "number") {
    requestConfig.temperature = options.temperature;
  }

  // 1. Attempt Primary Model: gemini-3.8-flash
  try {
    const response = await ai.models.generateContent({
      model: PRIMARY_MODEL,
      contents,
      config: Object.keys(requestConfig).length ? requestConfig : undefined,
    });

    if (response?.text) {
      return {
        text: response.text.trim(),
        modelUsed: PRIMARY_MODEL,
        success: true,
      };
    }
  } catch (primaryErr: any) {
    console.warn(
      `[AI-Audit] Primary model (${PRIMARY_MODEL}) failed: ${primaryErr?.message || primaryErr}. Falling back to ${FALLBACK_MODEL}...`
    );
  }

  // 2. Attempt Fallback Model: gemini-3.6-flash
  try {
    const fallbackResponse = await ai.models.generateContent({
      model: FALLBACK_MODEL,
      contents,
      config: Object.keys(requestConfig).length ? requestConfig : undefined,
    });

    if (fallbackResponse?.text) {
      return {
        text: fallbackResponse.text.trim(),
        modelUsed: FALLBACK_MODEL,
        success: true,
      };
    }
  } catch (fallbackErr: any) {
    console.error(
      `[AI-Audit] Fallback model (${FALLBACK_MODEL}) also failed: ${fallbackErr?.message || fallbackErr}`
    );
    return {
      text: null,
      modelUsed: null,
      success: false,
      error: fallbackErr?.message || "Both primary and fallback AI models failed.",
    };
  }

  return {
    text: null,
    modelUsed: null,
    success: false,
    error: "No output generated by AI models.",
  };
}

export interface CategorySpendSummary {
  category: string;
  label: string;
  amount: number;
  percentage: number;
}

export interface FinancialAuditInput {
  monthName: string;
  totalSpend: number;
  count: number;
  topCategory: { label: string; amount: number; percentage: number };
  categoryBreakdown: CategorySpendSummary[];
}

/**
 * Generates a concise, 1-2 sentence AI audit/insight from monthly spending data.
 */
export async function auditFinancialsWithAi(
  data: FinancialAuditInput
): Promise<string | null> {
  const breakdownStr = data.categoryBreakdown
    .map((c) => `- ${c.label}: ₹${c.amount} (${c.percentage}%)`)
    .join("\n");

  const prompt = `You are Perbudge's AI financial co-pilot.
Provide a sharp, encouraging 1-2 sentence observation or tip for this user's spending this month (${data.monthName}):
- Total spend: ₹${data.totalSpend.toLocaleString("en-IN")} across ${data.count} expenses
- Top category: ${data.topCategory.label} (₹${data.topCategory.amount.toLocaleString("en-IN")}, ${data.topCategory.percentage}% of spend)
- Categories:
${breakdownStr}

Rules:
- Max 2 short sentences.
- Direct, warm, practical for an Indian household.
- Amounts in ₹.
- Plain text only (do NOT use markdown asterisks or headings).`;

  try {
    const result = await generateWithModelFallback(prompt, {
      temperature: 0.6,
    });

    return result.success ? result.text : null;
  } catch (error) {
    console.error("[AI-Audit] Audit generation error:", error);
    return null;
  }
}
